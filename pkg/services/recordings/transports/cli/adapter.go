// Package cli defines the Recordings service's CLI adapter.
package cli

import (
	"context"
	"errors"
	"fmt"
	"io"
	"strconv"
	"strings"

	"github.com/portpowered/infinite-you/pkg/services/recordings"
	"github.com/portpowered/infinite-you/pkg/transports/cli/clidiag"
	factoryapi "github.com/portpowered/infinite-you/pkg/transports/http/generated"
)

// DefaultReportedFactorySessionID is the customer-visible session token used
// when planning default live recording targets for normal you run invocations.
const DefaultReportedFactorySessionID = "~default"

// InvocationRequest captures Recordings-relevant CLI inputs for record-path
// policy resolution. ResumePath identifies a historical recording to continue
// and is intentionally separate from ReplayPath, which remains read-only.
type InvocationRequest struct {
	RecordPath              string
	ReplayPath              string
	ResumePath              string
	DisableDefaultRecording bool
	HomeDir                 string
	RecordingTargetPlanner  recordings.LiveRecordingTargetPlanner
	CanonicalSessionID      string
	ReportedSessionID       string
}

// ResolvedRecordPath is the adapter-owned record-path resolution outcome.
type ResolvedRecordPath struct {
	ServicePath   string
	ReportedPath  string
	AutoGenerated bool
}

// Adapter owns Recordings CLI record/replay/--no-record invocation policy.
type Adapter interface {
	ResolveRecordPath(InvocationRequest) (ResolvedRecordPath, error)
	ResolveRecordPathWithContext(context.Context, InvocationRequest) (ResolvedRecordPath, error)
	ReportRecordingPathOnShutdown(io.Writer, ResolvedRecordPath)
	RecordingDiagnosticsLabel(ResolvedRecordPath, string) string
}

type defaultAdapter struct{}

// New constructs the Recordings CLI adapter injected into Cobra composition.
func New() Adapter {
	return defaultAdapter{}
}

func (defaultAdapter) ResolveRecordPath(request InvocationRequest) (ResolvedRecordPath, error) {
	return defaultAdapter{}.ResolveRecordPathWithContext(context.Background(), request)
}

func (defaultAdapter) ResolveRecordPathWithContext(
	ctx context.Context,
	request InvocationRequest,
) (ResolvedRecordPath, error) {
	if err := ValidateInvocationFlags(request); err != nil {
		return ResolvedRecordPath{}, err
	}
	resumePath := strings.TrimSpace(request.ResumePath)
	if strings.TrimSpace(request.RecordPath) != "" {
		return ResolvedRecordPath{ServicePath: request.RecordPath}, nil
	}
	if request.DisableDefaultRecording || strings.TrimSpace(request.ReplayPath) != "" {
		return ResolvedRecordPath{}, nil
	}
	if err := ctx.Err(); err != nil {
		return ResolvedRecordPath{}, err
	}
	if request.RecordingTargetPlanner == nil {
		return ResolvedRecordPath{}, fmt.Errorf("Recordings live recording target planner is required")
	}
	reportedSessionID := strings.TrimSpace(request.ReportedSessionID)
	if reportedSessionID == "" {
		reportedSessionID = DefaultReportedFactorySessionID
	}
	target, err := request.RecordingTargetPlanner.PlanLiveRecordingTarget(recordings.LiveRecordingTargetRequest{
		HomeDir:            request.HomeDir,
		CanonicalSessionID: request.CanonicalSessionID,
		ReportedSessionID:  reportedSessionID,
	})
	if err != nil {
		if resumePath != "" {
			return ResolvedRecordPath{}, fmt.Errorf("resolve resume successor recording path: %w", err)
		}
		return ResolvedRecordPath{}, fmt.Errorf("resolve default replay record path: %w", err)
	}
	if err := ctx.Err(); err != nil {
		return ResolvedRecordPath{}, err
	}
	if strings.TrimSpace(target.ServicePath) == "" {
		if resumePath != "" {
			return ResolvedRecordPath{}, fmt.Errorf("resolve resume successor recording path: planner returned an empty service path")
		}
		return ResolvedRecordPath{}, fmt.Errorf("resolve default replay record path: planner returned an empty service path")
	}
	return ResolvedRecordPath{
		ServicePath:   target.ServicePath,
		ReportedPath:  target.ReportedPath,
		AutoGenerated: true,
	}, nil
}

func (defaultAdapter) ReportRecordingPathOnShutdown(output io.Writer, resolved ResolvedRecordPath) {
	if output == nil || !resolved.AutoGenerated || strings.TrimSpace(resolved.ReportedPath) == "" {
		return
	}
	fmt.Fprintf(output, "Recording saved: %s\n", resolved.ReportedPath)
}

func (defaultAdapter) RecordingDiagnosticsLabel(resolved ResolvedRecordPath, replayPath string) string {
	switch {
	case strings.TrimSpace(replayPath) != "":
		return "replay"
	case strings.TrimSpace(resolved.ServicePath) == "":
		return "disabled"
	case resolved.AutoGenerated:
		return "default"
	default:
		return "explicit"
	}
}

// ValidateInvocationFlags rejects incompatible Recordings CLI flag combinations
// before runtime opening begins.
func ValidateInvocationFlags(request InvocationRequest) error {
	if strings.TrimSpace(request.ResumePath) != "" && strings.TrimSpace(request.ReplayPath) != "" {
		return clidiag.NewFlagConflictFailure("--resume", "--replay", nil)
	}
	if strings.TrimSpace(request.ResumePath) != "" && request.DisableDefaultRecording {
		return clidiag.NewFlagConflictFailure("--resume", "--no-record", nil)
	}
	if request.DisableDefaultRecording && strings.TrimSpace(request.RecordPath) != "" {
		return clidiag.NewFlagConflictFailure("--no-record", "--record", nil)
	}
	if strings.TrimSpace(request.RecordPath) != "" && strings.TrimSpace(request.ReplayPath) != "" {
		return &clidiag.LocalFailure{
			Code:    clidiag.FlagConflictFailureCode,
			Message: "--record and --replay cannot be used together",
		}
	}
	return nil
}

// replayStructuralCLIError keeps the Recordings-owned first-corrupt-event
// diagnostic intact at the local command boundary. It is intentionally a
// presentation adapter: structural classification and safe event context
// remain owned by Recordings, while the CLI exposes the actionable line and
// standard coded-error contract.
type replayStructuralCLIError struct {
	diagnostic recordings.ReplayArtifactDiagnostic
	cause      error
}

func (err *replayStructuralCLIError) Error() string {
	if err == nil {
		return ""
	}
	diagnostic := err.diagnostic
	code := strings.TrimSpace(string(diagnostic.Code))
	if code == "" {
		code = string(recordings.ReplayArtifactDiagnosticMalformed)
	}
	area := strings.TrimSpace(diagnostic.Area)
	path := strings.TrimSpace(diagnostic.Path)
	if area == "" {
		area = "events"
	}
	if path == "" {
		path = "events"
	}
	eventID := replayStructuralEventID(diagnostic.Message)
	action := strings.TrimSpace(diagnostic.Action)
	if action == "" {
		action = recordings.ReplayArtifactStructuralRepairAction
	}
	message := safeReplayStructuralMessage(diagnostic.Message)
	if message == "" {
		message = "recording event is structurally invalid"
	}
	return fmt.Sprintf(
		"Error: %s area=%s path=%s event=%s action=%s: %s",
		code, area, path, strconv.Quote(eventID), strconv.Quote(action), message,
	)
}

func (err *replayStructuralCLIError) Unwrap() error {
	if err == nil {
		return nil
	}
	return err.cause
}

func (err *replayStructuralCLIError) CLIErrorCode() string {
	if err == nil || strings.TrimSpace(string(err.diagnostic.Code)) == "" {
		return string(recordings.ReplayArtifactDiagnosticMalformed)
	}
	return string(err.diagnostic.Code)
}

func (err *replayStructuralCLIError) CLIErrorFamily() factoryapi.ErrorFamily {
	return factoryapi.ErrorFamilyBadRequest
}

func (err *replayStructuralCLIError) CLIErrorMessage() string {
	return err.Error()
}

// MapStructuralReplayFailure adapts a legacy replay structural failure to the
// shared CLI diagnostic contract while retaining the original cause chain.
func MapStructuralReplayFailure(cause error) error {
	if cause == nil {
		return nil
	}
	var diagnostic recordings.ReplayArtifactDiagnostic
	var inputErr *recordings.ReplayInputError
	if errors.As(cause, &inputErr) && inputErr != nil {
		if inputErr.Family != recordings.ReplayInputFamilyLegacy ||
			!isLegacyReplayStructuralDiagnostic(inputErr.Diagnostic) {
			return nil
		}
		diagnostic = inputErr.Diagnostic
	} else {
		var artifactErr *recordings.ReplayArtifactError
		if !errors.As(cause, &artifactErr) || artifactErr == nil {
			return nil
		}
		diagnostic = artifactErr.Diagnostic
		if !isLegacyReplayStructuralDiagnostic(diagnostic) {
			return nil
		}
	}
	if !isStructuralReplayDiagnostic(diagnostic.Code) {
		return nil
	}
	return &replayStructuralCLIError{diagnostic: diagnostic, cause: cause}
}

func isLegacyReplayStructuralDiagnostic(diagnostic recordings.ReplayArtifactDiagnostic) bool {
	return strings.TrimSpace(diagnostic.Area) == "events" &&
		strings.HasPrefix(strings.TrimSpace(diagnostic.Path), "events[")
}

func isStructuralReplayDiagnostic(code recordings.ReplayArtifactDiagnosticCode) bool {
	switch code {
	case recordings.ReplayArtifactDiagnosticMalformed,
		recordings.ReplayArtifactDiagnosticInvalidIdentity,
		recordings.ReplayArtifactDiagnosticInvalidOrder,
		recordings.ReplayArtifactDiagnosticMissingReference,
		recordings.ReplayArtifactDiagnosticForeignReference:
		return true
	default:
		return false
	}
}

func replayStructuralEventID(message string) string {
	const prefix = `event "`
	start := strings.Index(message, prefix)
	if start < 0 {
		return "unknown"
	}
	start += len(prefix)
	end := strings.IndexByte(message[start:], '"')
	if end < 0 {
		return "unknown"
	}
	eventID := strings.TrimSpace(message[start : start+end])
	if eventID == "" {
		return "unknown"
	}
	return eventID
}

func safeReplayStructuralMessage(message string) string {
	return strings.Join(strings.Fields(strings.TrimSpace(message)), " ")
}

var _ clidiag.FamilyCodedError = (*replayStructuralCLIError)(nil)
