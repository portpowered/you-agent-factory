func TestAdapterReportRecordingPathOnShutdownPreservesAcceptedPresentation(t *testing.T) {
	t.Parallel()

	adapter := recordingscli.New()
	var out bytes.Buffer

	adapter.ReportRecordingPathOnShutdown(&out, recordingscli.ResolvedRecordPath{
		ServicePath:   "/tmp/template.json",
		ReportedPath:  "/tmp/resolved.json",
		AutoGenerated: true,
	})
	if got := out.String(); got != "Recording saved: /tmp/resolved.json\n" {
		t.Fatalf("shutdown output = %q, want accepted recording saved presentation", got)
	}
}

