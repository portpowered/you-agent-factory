package discoverygen

import (
	"fmt"
	"go/format"
	"slices"
	"strconv"
	"strings"

	"github.com/portpowered/infinite-you/internal/contractjoiner"
	"github.com/portpowered/infinite-you/pkg/platform/generatedartifacts"
)

const (
	// DiscoveryJSONPath is the generated MCP discovery metadata artifact.
	DiscoveryJSONPath = "pkg/transports/mcp/generated/discovery.json"
	// DiscoveryGoPath is the generated runtime MCP discovery metadata surface.
	DiscoveryGoPath = "pkg/transports/mcp/generated/discovery.gen.go"
)

// DiscoveryArtifact returns deterministic generated MCP discovery metadata bytes.
func DiscoveryArtifact(repositoryRoot string) ([]byte, error) {
	metadata, err := discoveryMetadata(repositoryRoot)
	if err != nil {
		return nil, err
	}
	return contractjoiner.MarshalCanonicalJSON(metadata)
}

// DiscoveryGoArtifact returns deterministic generated Go discovery metadata.
func DiscoveryGoArtifact(repositoryRoot string) ([]byte, error) {
	metadata, err := discoveryMetadata(repositoryRoot)
	if err != nil {
		return nil, err
	}

	ids := make([]string, 0, len(metadata.Tools))
	for id := range metadata.Tools {
		ids = append(ids, id)
	}
	slices.Sort(ids)

	var source strings.Builder
	source.WriteString("// Code generated by mcpdiscoverygen. DO NOT EDIT.\n\n")
	source.WriteString("package generated\n\n")
	source.WriteString("import \"encoding/json\"\n\n")
	source.WriteString("// DiscoveryTool is one canonical generated MCP tools/list descriptor.\n")
	source.WriteString("type DiscoveryTool struct {\n\tID string\n\tName string\n\tDescription string\n\tInputSchema json.RawMessage\n}\n\n")
	source.WriteString("// PrimaryDiscovery returns canonical generated discovery in stable tool-ID order.\n")
	source.WriteString("func PrimaryDiscovery() []DiscoveryTool {\n\treturn []DiscoveryTool{\n")
	for _, id := range ids {
		tool := metadata.Tools[id]
		schema, marshalErr := contractjoiner.MarshalCanonicalJSON(tool.InputSchema)
		if marshalErr != nil {
			return nil, fmt.Errorf("marshal input schema for %s: %w", id, marshalErr)
		}
		fmt.Fprintf(&source, "\t\t{ID: %s, Name: %s, Description: %s, InputSchema: json.RawMessage(%s)},\n",
			strconv.Quote(tool.ID), strconv.Quote(tool.Name), strconv.Quote(tool.Description), strconv.Quote(string(schema)))
	}
	source.WriteString("\t}\n}\n")

	formatted, err := format.Source([]byte(source.String()))
	if err != nil {
		return nil, fmt.Errorf("format generated Go discovery metadata: %w", err)
	}
	return formatted, nil
}

func discoveryMetadata(repositoryRoot string) (DiscoveryMetadata, error) {
	resolved, err := LoadResolvedCatalog(repositoryRoot)
	if err != nil {
		return DiscoveryMetadata{}, err
	}
	metadata, err := ProjectDiscoveryFromCatalogDocument(resolved)
	if err != nil {
		return DiscoveryMetadata{}, err
	}
	if err := VerifyDiscoveryByteStability(metadata); err != nil {
		return DiscoveryMetadata{}, err
	}
	return metadata, nil
}

// Artifacts returns the complete deterministic MCP discovery output set.
// Filesystem persistence and drift inspection belong to the command-selected
// Platform artifact store.
func Artifacts(repositoryRoot string) ([]generatedartifacts.Artifact, error) {
	jsonPayload, err := DiscoveryArtifact(repositoryRoot)
	if err != nil {
		return nil, err
	}
	goPayload, err := DiscoveryGoArtifact(repositoryRoot)
	if err != nil {
		return nil, err
	}
	return []generatedartifacts.Artifact{
		{Path: DiscoveryJSONPath, Payload: jsonPayload},
		{Path: DiscoveryGoPath, Payload: goPayload},
	}, nil
}
