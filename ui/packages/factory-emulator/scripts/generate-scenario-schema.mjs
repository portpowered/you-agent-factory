import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const schemaPath = path.join(packageRoot, "schema", "scenario.schema.json");
const outputPath = path.join(
  packageRoot,
  "src",
  "generated",
  "scenario-schema.ts",
);
const checkOnly = process.argv.includes("--check");

function normalizeNewlines(value) {
  return value.replace(/\r\n/g, "\n");
}

const schema = JSON.parse(await readFile(schemaPath, "utf8"));
const expected = `/**
 * Generated by scripts/generate-scenario-schema.mjs from
 * schema/scenario.schema.json. Do not edit this file directly.
 */
export const generatedScenarioSchema = ${JSON.stringify(schema, null, 2)};
`;

if (checkOnly) {
  let current;
  try {
    current = normalizeNewlines(await readFile(outputPath, "utf8"));
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }
  if (current !== expected) {
    console.error(
      "Generated scenario schema is stale. Run `bun run generate` in ui/packages/factory-emulator.",
    );
    process.exitCode = 1;
  }
} else {
  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, expected, "utf8");
  console.log(`Generated ${path.relative(packageRoot, outputPath)}`);
}
