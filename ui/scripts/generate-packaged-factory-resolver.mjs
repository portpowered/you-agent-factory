import { access, mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const outputPath = path.resolve(
  scriptDirectory,
  "../src/features/packaged-factories/lib/generated/public-package-data.ts",
);
const packagePrefix = "@you-agent-factory/packaged-factories";

function resolvePublicSpecifier(specifier) {
  const resolved = import.meta.resolve(specifier);
  const resolvedURL = new URL(resolved);
  if (resolvedURL.protocol !== "file:") {
    throw new Error(
      `[packaged-factory-resolver] public export did not resolve to installed package data: ${specifier}`,
    );
  }
  return resolvedURL;
}

function assertManifestIdentity(input) {
  if (
    input?.formatVersion !== "1" ||
    !Array.isArray(input.factories) ||
    input.factories.some(
      (entry) =>
        typeof entry?.slug !== "string" ||
        !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(entry.slug),
    )
  ) {
    throw new Error(
      "[packaged-factory-resolver] public manifest cannot generate a supported resolver",
    );
  }
}

function generateResolver(input) {
  assertManifestIdentity(input);
  const slugs = [...input.factories]
    .map(({ slug }) => slug)
    .sort((left, right) => left.localeCompare(right));
  if (new Set(slugs).size !== slugs.length) {
    throw new Error(
      "[packaged-factory-resolver] public manifest contains duplicate slugs",
    );
  }

  const artifactImports = slugs.flatMap((slug, index) => [
    `import factory${index}Json from "${packagePrefix}/factories/${slug}.json";`,
    `import factory${index}Yaml from "${packagePrefix}/factories/${slug}.yaml?raw";`,
  ]);
  const artifactEntries = slugs.flatMap((slug, index) =>
    ["json", "yaml"].flatMap((format) => {
      const binding = `factory${index}${format === "json" ? "Json" : "Yaml"}`;
      const specifier = `${packagePrefix}/factories/${slug}.${format}`;
      const singleLine = `  ["${specifier}", ${binding}],`;
      return singleLine.length <= 80
        ? [singleLine]
        : ["  [", `    "${specifier}",`, `    ${binding},`, "  ],"];
    }),
  );

  return [
    "// Generated by scripts/generate-packaged-factory-resolver.mjs.",
    "// Run the generator after the published manifest changes.",
    "",
    ...artifactImports,
    `import manifest from "${packagePrefix}/manifest";`,
    `import factorySchema from "${packagePrefix}/schemas/factory.json";`,
    "",
    "import type {",
    "  PackagedFactoryPublicDataSource,",
    "  PackagedFactoryPublicExport,",
    '} from "../public-contract";',
    "",
    "const publicPackageValues = new Map<PackagedFactoryPublicExport, unknown>([",
    `  ["${packagePrefix}/manifest", manifest],`,
    `  ["${packagePrefix}/schemas/factory.json", factorySchema],`,
    ...artifactEntries,
    "]);",
    "",
    "export const packagedFactoryPublicDataSource: PackagedFactoryPublicDataSource =",
    "  {",
    "    async read(specifier) {",
    "      return publicPackageValues.get(specifier);",
    "    },",
    "  };",
    "",
  ].join("\n");
}

const manifest = JSON.parse(
  await readFile(resolvePublicSpecifier(`${packagePrefix}/manifest`), "utf8"),
);
assertManifestIdentity(manifest);
await access(resolvePublicSpecifier(`${packagePrefix}/schemas/factory.json`));
await Promise.all(
  manifest.factories.flatMap(({ slug }) =>
    ["json", "yaml"].map((format) =>
      access(
        resolvePublicSpecifier(`${packagePrefix}/factories/${slug}.${format}`),
      ),
    ),
  ),
);
const expected = generateResolver(manifest);
if (process.argv.includes("--check")) {
  const actual = await readFile(outputPath, "utf8").catch(() => "");
  if (actual !== expected) {
    throw new Error(
      "[packaged-factory-resolver] generated resolver is stale; run bun run generate:packaged-factory-resolver",
    );
  }
} else {
  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, expected);
}
