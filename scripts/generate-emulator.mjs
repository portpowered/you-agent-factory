import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import process from "node:process";

const repositoryRoot = resolve(import.meta.dirname, "..");
const sourcePath = join(
  repositoryRoot,
  "contracts",
  "factory-emulator",
  "scenario.schema.json",
);
const packageRoot = join(repositoryRoot, "packages", "factory-emulator");
const generatedSchemaPath = join(
  packageRoot,
  "generated",
  "factory-emulator-scenario.schema.json",
);
const generatedTypesPath = join(packageRoot, "src", "generated", "scenario.ts");
const generatedSchemaModulePath = join(
  packageRoot,
  "src",
  "generated",
  "scenario-schema.js",
);
const generatedSchemaDeclarationPath = join(
  packageRoot,
  "src",
  "generated",
  "scenario-schema.d.ts",
);

const schema = JSON.parse(readFileSync(sourcePath, "utf8"));
const version = schema.properties?.version?.const;
if (typeof version !== "string") {
  throw new Error("Scenario schema must declare a string version const.");
}

const generatedArtifacts = [
  { path: generatedSchemaPath, contents: readFileSync(sourcePath) },
  { path: generatedTypesPath, contents: generatedTypes(schema) },
  { path: generatedSchemaModulePath, contents: generatedSchemaModule(version) },
  {
    path: generatedSchemaDeclarationPath,
    contents: generatedSchemaDeclaration(version),
  },
];

if (process.argv.includes("--check")) {
  checkFreshness(generatedArtifacts);
} else {
  writeArtifacts(generatedArtifacts);
  console.log("[factory-emulator] Generated scenario contract artifacts.");
}

function writeArtifacts(artifacts) {
  for (const artifact of artifacts) {
    mkdirSync(dirname(artifact.path), { recursive: true });
    writeFileSync(artifact.path, artifact.contents);
  }
}

function checkFreshness(artifacts) {
  const staleArtifacts = artifacts.filter(
    ({ path, contents }) =>
      !existsSync(path) || !readFileSync(path).equals(Buffer.from(contents)),
  );
  if (staleArtifacts.length > 0) {
    console.error(
      "[factory-emulator] Generated scenario contract artifacts are stale: " +
        staleArtifacts.map(({ path }) => path).join(", ") +
        ". Run `npm --prefix packages/factory-emulator run generate` and commit the generated artifacts.",
    );
    process.exitCode = 1;
    return;
  }
  console.log("[factory-emulator] Generated scenario contract artifacts are fresh.");
}

function generatedTypes(authoredSchema) {
  const definitions = authoredSchema.$defs ?? {};
  const declarations = [
    `export type EmulatorScenarioVersion = ${schemaType(
      authoredSchema.properties.version,
    )};`,
    ...Object.entries(definitions).map(([name, definition]) =>
      namedDeclaration(definitionName(name), definition),
    ),
    namedDeclaration("EmulatorScenario", authoredSchema, {
      version: "EmulatorScenarioVersion",
    }),
  ];

  return `// Code generated by scripts/generate-emulator.mjs; DO NOT EDIT.\n\n${declarations.join("\n\n")}\n`;
}

function namedDeclaration(name, definition, propertyOverrides = {}) {
  if (definition.type === "object" && !definition.oneOf) {
    return `export interface ${name} ${objectBody(definition, propertyOverrides)}`;
  }
  return `export type ${name} =${unionType(definition)};`;
}

function unionType(definition) {
  if (!Array.isArray(definition.oneOf)) {
    return ` ${schemaType(definition)}`;
  }
  return definition.oneOf
    .map((variant) => `\n  | ${indentContinuation(schemaType(variant), 4)}`)
    .join("");
}

function schemaType(definition) {
  if (!definition || typeof definition !== "object") {
    throw new Error("Scenario schema contains an invalid type definition.");
  }
  if (typeof definition.$ref === "string") {
    return referencedType(definition.$ref);
  }
  if (Object.hasOwn(definition, "const")) {
    return JSON.stringify(definition.const);
  }
  if (Array.isArray(definition.oneOf)) {
    return definition.oneOf.map(schemaType).join(" | ");
  }
  if (definition.type === "string") {
    return "string";
  }
  if (definition.type === "integer" || definition.type === "number") {
    return "number";
  }
  if (definition.type === "boolean") {
    return "boolean";
  }
  if (definition.type === "array") {
    return `readonly ${schemaType(definition.items)}[]`;
  }
  if (definition.type === "object") {
    if (definition.additionalProperties === true) {
      return "Record<string, unknown>";
    }
    return objectBody(definition);
  }
  throw new Error(
    `Unsupported scenario schema type: ${definition.type ?? "unknown"}.`,
  );
}

function objectBody(definition, propertyOverrides = {}) {
  const required = new Set(definition.required ?? []);
  const properties = Object.entries(definition.properties ?? {}).map(
    ([name, property]) => {
      const optional = required.has(name) ? "" : "?";
      const type = propertyOverrides[name] ?? schemaType(property);
      const comment = constraintComment(property);
      return `${comment}  ${propertyName(name)}${optional}: ${type};`;
    },
  );
  return `{\n${properties.join("\n")}\n}`;
}

function referencedType(reference) {
  const prefix = "#/$defs/";
  if (!reference.startsWith(prefix)) {
    throw new Error(`Unsupported scenario schema reference: ${reference}.`);
  }
  return definitionName(reference.slice(prefix.length));
}

function definitionName(name) {
  const pascalName = name.replace(
    /(^|[^a-zA-Z0-9]+)([a-zA-Z0-9])/g,
    (_, _separator, letter) => letter.toUpperCase(),
  );
  return `Emulator${pascalName}`;
}

function propertyName(name) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name);
}

function indentContinuation(value, spaces) {
  return value.replaceAll("\n", `\n${" ".repeat(spaces)}`);
}

function constraintComment(definition) {
  const constraints = [];
  if (definition.description) constraints.push(definition.description);
  if (definition.format) constraints.push(`Format: ${definition.format}.`);
  if (definition.pattern) constraints.push(`Pattern: ${definition.pattern}.`);
  if (definition.minLength !== undefined) {
    constraints.push(`Minimum length: ${definition.minLength}.`);
  }
  if (definition.maxLength !== undefined) {
    constraints.push(`Maximum length: ${definition.maxLength}.`);
  }
  if (definition.minimum !== undefined) {
    constraints.push(`Minimum: ${definition.minimum}.`);
  }
  if (definition.minItems !== undefined) {
    constraints.push(`Minimum items: ${definition.minItems}.`);
  }
  return constraints.length === 0 ? "" : `  /** ${constraints.join(" ")} */\n`;
}

function generatedSchemaModule(supportedVersion) {
  return `// Code generated by scripts/generate-emulator.mjs; DO NOT EDIT.\n\nimport schema from "../../generated/factory-emulator-scenario.schema.json" with { type: "json" };\n\nexport const SUPPORTED_SCENARIO_VERSION = ${JSON.stringify(supportedVersion)};\nexport const scenarioSchema = schema;\n`;
}

function generatedSchemaDeclaration(supportedVersion) {
  return `// Code generated by scripts/generate-emulator.mjs; DO NOT EDIT.\n\nexport declare const SUPPORTED_SCENARIO_VERSION: ${JSON.stringify(supportedVersion)};\nexport declare const scenarioSchema: Readonly<Record<string, unknown>>;\n`;
}
