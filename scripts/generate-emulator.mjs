import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import process from "node:process";

const repositoryRoot = resolve(import.meta.dirname, "..");
const sourcePath = join(
  repositoryRoot,
  "contracts",
  "factory-emulator",
  "scenario.schema.json",
);
const packageRoot = join(repositoryRoot, "packages", "factory-emulator");
const generatedSchemaPath = join(
  packageRoot,
  "generated",
  "factory-emulator-scenario.schema.json",
);
const generatedTypesPath = join(packageRoot, "src", "generated", "scenario.ts");
const generatedSchemaModulePath = join(
  packageRoot,
  "src",
  "generated",
  "scenario-schema.js",
);
const generatedSchemaDeclarationPath = join(
  packageRoot,
  "src",
  "generated",
  "scenario-schema.d.ts",
);

const schema = JSON.parse(readFileSync(sourcePath, "utf8"));
const version = schema.properties?.version?.const;
if (typeof version !== "string") {
  throw new Error("Scenario schema must declare a string version const.");
}

for (const path of [
  generatedSchemaPath,
  generatedTypesPath,
  generatedSchemaModulePath,
  generatedSchemaDeclarationPath,
]) {
  mkdirSync(dirname(path), { recursive: true });
}

copyFileSync(sourcePath, generatedSchemaPath);
writeFileSync(generatedTypesPath, generatedTypes(version));
writeFileSync(generatedSchemaModulePath, generatedSchemaModule(version));
writeFileSync(
  generatedSchemaDeclarationPath,
  generatedSchemaDeclaration(version),
);

console.log("[factory-emulator] Generated scenario contract artifacts.");

function generatedTypes(supportedVersion) {
  return `// Code generated by scripts/generate-emulator.mjs; DO NOT EDIT.\n\nexport type EmulatorScenarioVersion = ${JSON.stringify(supportedVersion)};\n\nexport type EmulatorMatcher =\n  | { kind: "all" }\n  | { kind: "workType"; workType: string }\n  | { kind: "submissionId"; submissionId: string };\n\nexport type EmulatorLineageCursor =\n  | { kind: "initialSubmission"; submissionId: string }\n  | { kind: "scriptedOutcome"; ruleId: string; outcomeIndex: number };\n\nexport type EmulatorOutcome =\n  | { kind: "complete"; output?: Record<string, unknown>; lineageCursor?: EmulatorLineageCursor }\n  | { kind: "reject"; reason: string };\n\nexport type EmulatorExhaustionBehavior =\n  | { kind: "repeatLast" }\n  | { kind: "useUnmatchedBehavior" }\n  | { kind: "reject"; reason: string };\n\nexport type EmulatorUnmatchedBehavior =\n  | { kind: "ignore" }\n  | { kind: "reject"; reason: string };\n\nexport interface EmulatorInitialSubmission {\n  id: string;\n  workType: string;\n  input?: Record<string, unknown>;\n}\n\nexport interface EmulatorRule {\n  id: string;\n  match: EmulatorMatcher;\n  outcomes: readonly EmulatorOutcome[];\n  exhaustionBehavior: EmulatorExhaustionBehavior;\n}\n\nexport interface EmulatorScenario {\n  version: EmulatorScenarioVersion;\n  id: string;\n  seed: string;\n  startAt: string;\n  initialSubmissions?: readonly EmulatorInitialSubmission[];\n  rules: readonly EmulatorRule[];\n  unmatchedBehavior: EmulatorUnmatchedBehavior;\n  activityLabel?: string;\n}\n`;
}

function generatedSchemaModule(supportedVersion) {
  return `// Code generated by scripts/generate-emulator.mjs; DO NOT EDIT.\n\nimport schema from "../../generated/factory-emulator-scenario.schema.json" with { type: "json" };\n\nexport const SUPPORTED_SCENARIO_VERSION = ${JSON.stringify(supportedVersion)};\nexport const scenarioSchema = schema;\n`;
}

function generatedSchemaDeclaration(supportedVersion) {
  return `// Code generated by scripts/generate-emulator.mjs; DO NOT EDIT.\n\nexport declare const SUPPORTED_SCENARIO_VERSION: ${JSON.stringify(supportedVersion)};\nexport declare const scenarioSchema: Readonly<Record<string, unknown>>;\n`;
}
