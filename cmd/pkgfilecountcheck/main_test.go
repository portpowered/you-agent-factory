func TestRunSucceedsWithExactlyPackageFileLimit(t *testing.T) {
	t.Parallel()

	repoRoot := t.TempDir()
	writePackageFiles(t, repoRoot, "pkg/service", 15)

	stdout := &bytes.Buffer{}
	stderr := &bytes.Buffer{}
	err := run(config{
		root:             repoRoot,
		packageRoot:      defaultScanRoot,
		packageFileLimit: defaultPackageFileLimit,
	}, stdout, stderr)
	if err != nil {
		t.Fatalf("run() error = %v, want nil", err)
	}
	if got := stdout.String(); !strings.Contains(got, "package file-count passed (package files <= 15)") {
		t.Fatalf("run() stdout = %q, want success message with default limit", got)
	}
	if got := stderr.String(); got != "" {
		t.Fatalf("run() stderr = %q, want empty", got)
	}
}

func TestRunFailsWhenPackageExceedsPackageFileLimit(t *testing.T) {
	t.Parallel()

	repoRoot := t.TempDir()
	writePackageFiles(t, repoRoot, "pkg/service", 16)

	stdout := &bytes.Buffer{}
	stderr := &bytes.Buffer{}
	err := run(config{
		root:             repoRoot,
		packageRoot:      defaultScanRoot,
		packageFileLimit: defaultPackageFileLimit,
	}, stdout, stderr)
	if err == nil {
		t.Fatal("run() error = nil, want package file-count violation")
	}
	if got := stdout.String(); got != "" {
		t.Fatalf("run() stdout = %q, want empty", got)
	}

	errOutput := stderr.String()
	wantOutput := strings.Join([]string{
		"[agent-factory:pkg-file-count] oversized package: pkg/service",
		"  package files: 16",
		"  limit: 15",
		"  counted files:",
		"    - pkg/service/file_01.go",
		"    - pkg/service/file_02.go",
		"    - pkg/service/file_03.go",
		"    - pkg/service/file_04.go",
		"    - pkg/service/file_05.go",
		"    - pkg/service/file_06.go",
		"    - pkg/service/file_07.go",
		"    - pkg/service/file_08.go",
		"    - pkg/service/file_09.go",
		"    - pkg/service/file_10.go",
		"    - pkg/service/file_11.go",
		"    - pkg/service/file_12.go",
		"    - pkg/service/file_13.go",
		"    - pkg/service/file_14.go",
		"    - pkg/service/file_15.go",
		"    - pkg/service/file_16.go",
		"",
	}, "\n")
	if errOutput != wantOutput {
		t.Fatalf("run() stderr = %q, want deterministic package count details %q", errOutput, wantOutput)
	}
	if got := err.Error(); got != "[agent-factory:pkg-file-count] found 1 package file-count violation(s)" {
		t.Fatalf("run() error = %q, want violation count", got)
	}
}

