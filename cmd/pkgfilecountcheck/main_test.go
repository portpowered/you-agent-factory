func TestRunReportsMultiplePackagesDeterministically(t *testing.T) {
	t.Parallel()

	repoRoot := t.TempDir()
	writePackageFiles(t, repoRoot, "pkg/zeta", 16)
	writePackageFiles(t, repoRoot, "pkg/alpha", 16)

	stderr := &bytes.Buffer{}
	err := run(config{
		root:             repoRoot,
		packageRoot:      defaultScanRoot,
		packageFileLimit: defaultPackageFileLimit,
	}, &bytes.Buffer{}, stderr)
	if err == nil {
		t.Fatal("run() error = nil, want package file-count violations")
	}

	errOutput := stderr.String()
	alphaIndex := strings.Index(errOutput, "[agent-factory:pkg-file-count] oversized package: pkg/alpha")
	zetaIndex := strings.Index(errOutput, "[agent-factory:pkg-file-count] oversized package: pkg/zeta")
	if alphaIndex < 0 || zetaIndex < 0 || alphaIndex > zetaIndex {
		t.Fatalf("run() stderr = %q, want packages reported in path order", errOutput)
	}
	if got := strings.Count(errOutput, "  counted files:\n"); got != 2 {
		t.Fatalf("run() stderr = %q, want counted file section for each package", errOutput)
	}
	if got := err.Error(); got != "[agent-factory:pkg-file-count] found 2 package file-count violation(s)" {
		t.Fatalf("run() error = %q, want two violation count", got)
	}
}

func TestMakePkgFileCountTargetFailsForOversizedOwnedPackage(t *testing.T) {
	repoRoot := filepath.Clean(filepath.Join("..", ".."))
	fixtureRoot := t.TempDir()
	writePackageFiles(t, fixtureRoot, "pkg/service", 16)

	cmd := exec.Command("make", "pkg-file-count", "PACKAGE_FILE_COUNT_ROOT="+fixtureRoot)
	cmd.Dir = repoRoot
	output, err := cmd.CombinedOutput()
	if err == nil {
		t.Fatalf("make pkg-file-count succeeded, want oversized package failure; output:\n%s", output)
	}

	got := string(output)
	for _, want := range []string{
		"go run ./cmd/pkgfilecountcheck -root " + fixtureRoot,
		"[agent-factory:pkg-file-count] oversized package: pkg/service",
		"  package files: 16",
		"  limit: 15",
		"[agent-factory:pkg-file-count] found 1 package file-count violation(s)",
	} {
		if !strings.Contains(got, want) {
			t.Fatalf("make pkg-file-count output = %q, want substring %q", got, want)
		}
	}
}

