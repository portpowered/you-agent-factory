func TestScanAllowsInjectedAndExplicitNoopLoggers(t *testing.T) {
	root := fixtureRepository(t, map[string]string{
		"pkg/runtime/injected.go": `package runtime
import (
  "github.com/portpowered/infinite-you/pkg/platform/logging"
  "go.uber.org/zap"
)
type runtime struct { logger logging.Logger }
func newRuntime(logger logging.Logger) runtime { return runtime{logger: logger} }
func disabled() logging.Logger { return logging.NoopLogger{} }
func disabledZap() *zap.Logger { return zap.NewNop() }`,
		"pkg/runtime/generated.go":     "// Code generated by fixture. DO NOT EDIT.\npackage runtime\nimport \"go.uber.org/zap\"\nvar _ = zap.L()\n",
		"pkg/runtime/injected_test.go": "package runtime\nimport \"go.uber.org/zap\"\nvar _ = zap.L()\n",
	})

	findings, err := scan(root)
	if err != nil {
		t.Fatalf("scan fixture: %v", err)
	}
	if len(findings) != 0 {
		t.Fatalf("injected or explicit no-op logging produced findings: %v", findings)
	}
}

func TestScanAllowsNarrowCompositionOwners(t *testing.T) {
	root := fixtureRepository(t, map[string]string{
		"pkg/transports/cli/root.go": `package cli
import "github.com/portpowered/infinite-you/pkg/platform/logging"
func compose() { _, _ = logging.BuildLogger(false, false) }`,
		"pkg/transports/cli/terminalpolicy/policy.go": `package terminalpolicy
func compose() { _, _ = logging.BuildLogger(false, false) }`,
		"pkg/platform/logging/logger.go": `package logging
import "go.uber.org/zap"
func build() { _, _ = zap.NewProduction() }`,
	})

	findings, err := scan(root)
	if err != nil {
		t.Fatalf("scan fixture: %v", err)
	}
	if len(findings) != 0 {
		t.Fatalf("approved composition produced findings: %v", findings)
	}
}

func fixtureRepository(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	for relative, contents := range files {
		path := filepath.Join(root, filepath.FromSlash(relative))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatalf("create fixture directory: %v", err)
		}
		if err := os.WriteFile(path, []byte(contents), 0o600); err != nil {
			t.Fatalf("write fixture %s: %v", relative, err)
		}
	}
	return root
}

func containsFinding(findings []string, want string) bool {
	for _, finding := range findings {
		if strings.Contains(finding, want) {
			return true
		}
	}
	return false
}
