func TestRunAcceptsCanonicalRootsAndExcludedAuthoringContent(t *testing.T) {
	root := fixtureRepository(t)
	writeFixture(t, root, "examples/demo/factory.json", `{"name":"@you/example"}`)
	writeFixture(t, root, "tests/testdata/duplicate/factory.json", `{"name":"@you/goal"}`)
	writeFixture(t, root, "factory/factory.json", `{"name":"@you/customer-scaffold"}`)
	writeFixture(t, root, "dist/factory.json", `{"name":"@you/generated"}`)

	var stdout bytes.Buffer
	if err := run(config{root: root}, &stdout); err != nil {
		t.Fatalf("run() error = %v", err)
	}
	if !strings.Contains(stdout.String(), "source boundary holds for 7 shipped Factories") {
		t.Fatalf("stdout = %q, want success diagnostic", stdout.String())
	}
}

func TestRunAcceptsYAMLRootDocument(t *testing.T) {
	root := fixtureRepository(t)
	goalDir := filepath.Join(root, filepath.FromSlash(authoredBoundary), "goal")
	if err := os.Remove(filepath.Join(goalDir, "factory.json")); err != nil {
		t.Fatalf("remove JSON root: %v", err)
	}
	writeFixture(t, root, authoredBoundary+"/goal/factory.yaml", "name: '@you/goal'\n")

	if err := run(config{root: root}, &bytes.Buffer{}); err != nil {
		t.Fatalf("run() error = %v", err)
	}
}

func TestRunRejectsAmbiguousRootDocumentsWithActionablePaths(t *testing.T) {
	root := fixtureRepository(t)
	writeFixture(t, root, authoredBoundary+"/goal/factory.yaml", "name: '@you/goal'\n")

	err := run(config{root: root}, &bytes.Buffer{})
	assertErrorContains(t, err,
		authoredBoundary+"/goal contains 2 root Factory documents (factory.json, factory.yaml)",
		"keep exactly one of factory.json, factory.yaml, or factory.yml",
	)
}

func TestRunRejectsFirstPartyDefinitionOutsideAuthoredBoundary(t *testing.T) {
	root := fixtureRepository(t)
	writeFixture(t, root, "pkg/services/factory_definitions/packages/new/factory.yml", "name: '@you/new'\n")

	err := run(config{root: root}, &bytes.Buffer{})
	assertErrorContains(t, err,
		"pkg/services/factory_definitions/packages/new/factory.yml",
		`declares shipped first-party Factory "@you/new"`,
		authoredBoundary,
	)
}

func TestRunRejectsFirstPartyDefinitionAuthoredAsGoLiteral(t *testing.T) {
	root := fixtureRepository(t)
	writeFixture(t, root, "pkg/services/factory_definitions/packages/new/builtin.go", "package new\nvar definition = []byte(`{\"name\":\"@you/new-literal\"}`)\n")

	err := run(config{root: root}, &bytes.Buffer{})
	assertErrorContains(t, err,
		"pkg/services/factory_definitions/packages/new/builtin.go",
		`declares shipped first-party Factory "@you/new-literal"`,
		authoredBoundary,
	)
}

