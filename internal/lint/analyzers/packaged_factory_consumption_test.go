func TestPackagedFactoryConsumptionCompiler(t *testing.T) {
	const root = "github.com/portpowered/infinite-you/"
	files := map[string]string{
		root + "packages/packaged-factories/p.go": "package publication\nconst Bytes = 1\n",
		root + "internal/packagedfactorycatalog/catalog.go": `package packagedfactorycatalog
import _ "github.com/portpowered/infinite-you/packages/packaged-factories"
func LoadPublishedDefinitionCatalog() {}
func Other() {}
`,
	}
	paths := []string{root + "packages/packaged-factories", root + "internal/packagedfactorycatalog"}
	add := func(path, source string) {
		files[root+path] = source
		paths = append(paths, root+filepath.ToSlash(filepath.Dir(path)))
	}
	publication := packagedConsumptionPublicationFixtures(add)
	catalog := `import c "github.com/portpowered/infinite-you/internal/packagedfactorycatalog"
`
	for path := range packagedLoaderFiles {
		add(path, "package allowed\n"+catalog+"func allowed() { c.LoadPublishedDefinitionCatalog() }\n")
	}
	add("pkg/wire/neighbor.go", "package allowed\n"+catalog+`func neighbor() {
 c.LoadPublishedDefinitionCatalog() // want "packaged-factory-catalog-loader:.*Factory Definitions catalog operations"
}
`)
	add("internal/consumer/normal.go", `package consumer
import "github.com/portpowered/infinite-you/internal/packagedfactorycatalog"
func normal() {
 packagedfactorycatalog.LoadPublishedDefinitionCatalog() // want "packaged-factory-catalog-loader:"
}
`)
	add("internal/consumer/alias.go", "package consumer\n"+catalog+`func alias() {
 (c.LoadPublishedDefinitionCatalog)() // want "packaged-factory-catalog-loader:"
 c.Other()
 c := struct { LoadPublishedDefinitionCatalog func() }{func(){}}
 c.LoadPublishedDefinitionCatalog()
}
`)
	add("internal/consumer/catalog_dot.go", `package consumer
import . "github.com/portpowered/infinite-you/internal/packagedfactorycatalog"
func dot() {
 LoadPublishedDefinitionCatalog() // want "packaged-factory-catalog-loader:"
}
`)
	add("internal/unrelated/unrelated.go", "package unrelated\n"+catalog+`type local struct{}
func (local) LoadPublishedDefinitionCatalog() {}
func LoadPublishedDefinitionCatalog() {}
func unrelated() { c.Other(); local{}.LoadPublishedDefinitionCatalog(); LoadPublishedDefinitionCatalog() }
`)
	files["example.com/packagedfactorycatalog/catalog.go"] = "package packagedfactorycatalog\nfunc LoadPublishedDefinitionCatalog() {}\n"
	add("internal/similar/source.go", `package similar
import "example.com/packagedfactorycatalog"
func similar() { packagedfactorycatalog.LoadPublishedDefinitionCatalog() }
`)

	add("internal/tagged/base.go", "package tagged\n")
	add("internal/tagged/tagged.go", "//go:build integration\n\npackage tagged\n"+catalog+`func tagged() {
 c.LoadPublishedDefinitionCatalog() // want "packaged-factory-catalog-loader:"
}
`)
	packagedConsumptionExemptFixtures(add, catalog, publication)
	dir, cleanup, err := analysistest.WriteFiles(files)
	if err != nil {
		t.Fatal(err)
	}
	defer cleanup()

	t.Run("default", func(t *testing.T) { analysistest.Run(t, dir, PackagedFactoryConsumption, paths...) })
	t.Run("integration", func(t *testing.T) {
		t.Setenv("GOFLAGS", "-tags=integration")
		analysistest.Run(t, dir, PackagedFactoryConsumption, paths...)
	})
}

func packagedConsumptionPublicationFixtures(add func(string, string)) string {
	publication := `import p "github.com/portpowered/infinite-you/packages/packaged-factories" // want "packaged-factory-direct-publication:.*Factory Definitions catalog resolve/install"
var _ = p.Bytes
`
	add("internal/consumer/named.go", "package consumer\n"+publication)
	add("internal/consumer/blank.go", `package consumer
import _ "github.com/portpowered/infinite-you/packages/packaged-factories" // want "packaged-factory-direct-publication:"
`)
	add("internal/consumer/dot.go", `package consumer
import . "github.com/portpowered/infinite-you/packages/packaged-factories" // want "packaged-factory-direct-publication:"
var _ = Bytes
`)
	add("packages/packaged-factories/child/p.go", "package child\n"+publication)
	add("internal/packagedfactorycatalog/child/p.go", "package child\n"+publication)
	return publication
}

func packagedConsumptionExemptFixtures(add func(string, string), catalog, publication string) {
	exempt := "package exempt\n" + catalog + "import _ \"github.com/portpowered/infinite-you/packages/packaged-factories\"\nfunc bypass() { c.LoadPublishedDefinitionCatalog() }\n"
	add("internal/exempt/generated.go", "// Code generated by fixture. DO NOT EDIT.\n"+exempt)
	add("internal/exempt/empty.go", "package exempt\n")
	add("internal/exempt/bypass_test.go", strings.ReplaceAll(exempt, "func bypass()", "func testBypass()"))
	add("internal/external/empty.go", "package external\n")
	add("internal/external/external_test.go", strings.ReplaceAll(exempt, "package exempt", "package external_test"))
	for _, dir := range []string{".git", ".artifacts", "coverage", "dist", "examples", "fixtures", "node_modules", "testdata", "tests", "vendor"} {
		add("internal/"+strings.ToUpper(dir)+"/p.go", exempt)
	}
	add("factory/p.go", exempt)
	add("internal/factory/p.go", "package nested\n"+publication)
	add("internal/native/native_"+runtime.GOOS+".go", "package native\n"+catalog+`func native() {
 c.LoadPublishedDefinitionCatalog() // want "packaged-factory-catalog-loader:"
}
`)
}

func TestPackagedFactoryConsumptionMetadata(t *testing.T) {
	for _, tc := range []struct {
		name, source string
		want         int
	}{
		{"tagged.go", "//go:build special\n\npackage fixture\nimport _ \"github.com/portpowered/infinite-you/packages/packaged-factories\"\nthis body need not parse", 1},
		{"generated.go", "// Code generated by fixture. DO NOT EDIT.\npackage fixture\nimport _ \"github.com/portpowered/infinite-you/packages/packaged-factories\"", 0},
		{"tagged_test.go", "package fixture\nimport _ \"github.com/portpowered/infinite-you/packages/packaged-factories\"", 0},
	} {
		t.Run(tc.name, func(t *testing.T) {
			fset := token.NewFileSet()
			selected, err := parser.ParseFile(fset, "selected.go", "package fixture", parser.ParseComments)
			if err != nil {
				t.Fatal(err)
			}
			name := filepath.Join(t.TempDir(), tc.name)
			var got []analysis.Diagnostic
			reads := 0
			pass := &analysis.Pass{Analyzer: PackagedFactoryConsumption, Fset: fset, Files: []*ast.File{selected}, Pkg: types.NewPackage(modulePrefix+"internal/fixture", "fixture"),
				IgnoredFiles: []string{name}, OtherFiles: []string{name},
				ReadFile: func(string) ([]byte, error) { reads++; return []byte(tc.source), nil },
				Report:   func(d analysis.Diagnostic) { got = append(got, d) },
			}
			if _, err := runPackagedFactoryConsumption(pass); err != nil {
				t.Fatal(err)
			}
			if len(got) != tc.want {
				t.Fatalf("diagnostics=%v", got)
			}
			if tc.want == 1 && (reads != 1 || fset.Position(got[0].Pos).Line != 4) {
				t.Fatalf("reads=%d diagnostic=%v", reads, got)
			}
		})
	}
}

func TestPackagedFactoryConsumptionMetadataFailure(t *testing.T) {
	fset := token.NewFileSet()
	selected, err := parser.ParseFile(fset, "selected.go", "package fixture", 0)
	if err != nil {
		t.Fatal(err)
	}
	failure := errors.New("compiler metadata unavailable")
	pass := &analysis.Pass{Analyzer: PackagedFactoryConsumption, Fset: fset, Files: []*ast.File{selected}, Pkg: types.NewPackage(modulePrefix+"internal/fixture", "fixture"), IgnoredFiles: []string{"ignored.go"},
		ReadFile: func(string) ([]byte, error) { return nil, failure },
	}
	if _, err := runPackagedFactoryConsumption(pass); !errors.Is(err, failure) {
		t.Fatalf("error=%v", err)
	}
	pass.ReadFile = func(string) ([]byte, error) { return []byte("package fixture\nimport ????"), nil }
	if _, err := runPackagedFactoryConsumption(pass); err == nil {
		t.Fatal("malformed import must fail")
	}
}
