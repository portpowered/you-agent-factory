func TestServiceShapeBaseline(t *testing.T) {
	const unit = "pkg/services/shape"
	const export = "service-root-exported-function|" + unit + "|" + unit + "/service.go#Start"
	const deleted = "service-root-exported-function|" + unit + "|" + unit + "/deleted.go#Gone"
	useFixtures(t, export, deleted)
	pass, diagnostics := shapePass(t, unit, map[string]string{
		"service.go": "package shape\ntype Service interface{}\nfunc Start() {}\nfunc New() {}\n",
	})
	if _, err := ServiceShape.Run(pass); err != nil {
		t.Fatal(err)
	}
	if len(*diagnostics) != 2 {
		t.Fatalf("want new and stale diagnostics, got %v", *diagnostics)
	}
	if got := (*diagnostics)[0]; !strings.Contains(got.Message, unit+"/service.go#New") || pass.Fset.Position(got.Pos).Line != 4 {
		t.Fatalf("new finding must identify exact export and declaration: %+v", got)
	}
	if got := (*diagnostics)[1]; !strings.Contains(got.Message, "stale baseline entry `"+deleted+"`") {
		t.Fatalf("deleted source in analyzed unit must be stale: %+v", got)
	}
}

func TestServiceShapeIgnoredDeclarations(t *testing.T) {
	const unit = "pkg/services/shape"
	const count = "service-root-interface-count|" + unit + "|" + unit + "/base.go:Service," + unit + "/tagged.go:Other"
	const export = "service-root-exported-function|" + unit + "|" + unit + "/tagged.go#New"
	useFixtures(t, count, export)
	pass, diagnostics := shapePass(t, unit, map[string]string{
		"base.go": "package shape\ntype Service interface{}\n",
	})
	pass.IgnoredFiles = []string{"/fixture/" + unit + "/tagged.go"}
	if _, err := ServiceShape.Run(pass); err != nil {
		t.Fatal(err)
	}
	if len(*diagnostics) != 0 {
		t.Fatalf("excluded declaration debt must not be falsely stale: %v", *diagnostics)
	}
	selected, selectedDiagnostics := shapePass(t, unit, map[string]string{
		"base.go":   "package shape\ntype Service interface{}\n",
		"tagged.go": "package shape\ntype Other interface{}\nfunc New() {}\n",
	})
	ServiceShape.Run(selected)
	if len(*selectedDiagnostics) != 0 {
		t.Fatalf("selected exact debt must be accepted: %v", *selectedDiagnostics)
	}
	selected.Files[1].Decls = selected.Files[1].Decls[:1]
	ServiceShape.Run(selected)
	if len(*selectedDiagnostics) != 1 || !strings.Contains((*selectedDiagnostics)[0].Message, "stale baseline entry `"+export+"`") {
		t.Fatalf("selected repaired export must be stale: %v", *selectedDiagnostics)
	}
}

