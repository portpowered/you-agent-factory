func TestServiceShapeRecursiveLocations(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct {
		unit, root string
		container  bool
		unexpected []string
	}{
		{"pkg/services/a", "pkg/services/a", false, nil},
		{"pkg/services/a/internal/services/b/internal/services/c", "pkg/services/a/internal/services/b/internal/services/c", false, nil},
		{"pkg/services/a/internal/services", "pkg/services/a", true, nil},
		{"pkg/services/a/internal/implementation", "", false, nil},
		{"pkg/services/a/wire", "", false, nil},
		{"pkg/services/a/transports/http", "", false, nil},
		{"pkg/services/a/extra/sub", "", false, []string{"pkg/services/a/extra"}},
		{"pkg/services/a/services/b/services", "pkg/services/a/services/b", true, []string{"pkg/services/a/services", "pkg/services/a/services/b/services"}},
		{"pkg/services", "", false, nil},
		{"pkg/platform/a", "", false, nil},
	} {
		root, container, unexpected := serviceLocation(tc.unit)
		if root != tc.root || container != tc.container || !reflect.DeepEqual(unexpected, tc.unexpected) {
			t.Errorf("%s: got (%q, %v, %v)", tc.unit, root, container, unexpected)
		}
	}
}

func shapePass(t *testing.T, unit string, sources map[string]string) (*analysis.Pass, *[]analysis.Diagnostic) {
	t.Helper()
	fset := token.NewFileSet()
	var files []*ast.File
	// Stable filenames make declaration and diagnostic ordering reproducible.
	names := make([]string, 0, len(sources))
	for name := range sources {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		source := sources[name]
		file, err := parser.ParseFile(fset, "/fixture/"+unit+"/"+name, source, parser.ParseComments)
		if err != nil {
			t.Fatal(err)
		}
		files = append(files, file)
	}
	var diagnostics []analysis.Diagnostic
	return &analysis.Pass{
		Analyzer: ServiceShape, Fset: fset, Files: files, Pkg: types.NewPackage("m/"+unit, "shape"),
		Report: func(d analysis.Diagnostic) { diagnostics = append(diagnostics, d) },
	}, &diagnostics
}
