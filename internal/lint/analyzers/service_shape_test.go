func TestServiceShapeContainerFiles(t *testing.T) {
	useFixtures(t)
	for _, unit := range []string{
		"pkg/services/shape/internal/services", "pkg/services/shape/services",
	} {
		pass, diagnostics := shapePass(t, unit, map[string]string{
			"container.go":      "package services\n",
			"generated.go":      "// Code generated by fixture. DO NOT EDIT.\npackage services\n",
			"container_test.go": "package services\n",
		})
		ServiceShape.Run(pass)
		var targets []string
		for _, diagnostic := range *diagnostics {
			if strings.Contains(diagnostic.Message, "service-container-go-file:") {
				targets = append(targets, pass.Fset.Position(diagnostic.Pos).Filename)
			}
		}
		if len(targets) != 3 {
			t.Fatalf("every compiled container source must fail, including generated/tests: %v", *diagnostics)
		}
	}
}

