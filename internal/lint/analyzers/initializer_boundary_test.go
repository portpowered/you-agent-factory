func TestBehaviorInitializerZeroDebt(t *testing.T) {
	useFixtures(t)
	// No legacy debt store exists for these rules. Even a fabricated allowance
	// must not suppress an occurrence, including repeated fields on one line.
	baseline = func() map[string]struct{} {
		return parseBaseline("initializer-boundary-product-lifecycle-slot|pkg/initializer|API")
	}
	pass, diagnostics := shapePass(t, "pkg/initializer", map[string]string{
		"core.go": "package initializer; type One struct{ API any }; type Two struct{ API any }",
	})
	pass.Analyzer = Behavior
	pass.TypesInfo = &types.Info{}
	if _, err := Behavior.Run(pass); err != nil {
		t.Fatal(err)
	}
	if len(*diagnostics) != 2 {
		t.Fatalf("want both forbidden occurrences despite baseline, got %v", *diagnostics)
	}
}
