func TestTransportRecordedSites(t *testing.T) {
	for _, tc := range []struct {
		name, source, filename string
	}{
		{"exact", "func run(ctx context.Context) { _, _ = context.WithCancel(ctx) }", "a.go"},
		{"more", `func run(ctx context.Context) {
 _, _ = context.WithCancel(ctx) // want "transport-recorded-site:.*count=2"
 _, _ = context.WithCancel(ctx)
}`, "a.go"},
		{"neighbor", `func run(ctx context.Context) { _, _ = context.WithCancel(ctx) } // want "transport-recorded-site:.*b.go"`, "b.go"},
		{"removed", "var _ context.Context", "a.go"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			const unit = "pkg/transports/sites"
			useFixtures(t, "transport-lifecycle|"+unit+"|context.WithCancel",
				"transport-recorded-site|"+unit+"|"+unit+"/a.go#transport-lifecycle#context.WithCancel::count=1")
			pkg := "package sites"
			if tc.name != "exact" {
				pkg += ` // want "stale baseline entry.*transport-recorded-site"`
			}
			if tc.name == "removed" {
				pkg += ` "stale baseline entry.*transport-lifecycle"`
			}
			source := fmt.Sprintf("%s\nimport \"context\"\n%s\n", pkg, tc.source)
			dir, cleanup, err := analysistest.WriteFiles(map[string]string{"m/" + unit + "/" + tc.filename: source})
			if err != nil {
				t.Fatal(err)
			}
			t.Cleanup(cleanup)
			analysistest.Run(t, dir, Behavior, "m/"+unit)
		})
	}
}

