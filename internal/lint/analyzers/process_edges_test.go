func TestProcessEdgesExactEffectAllowances(t *testing.T) {
	useFixtures(t)
	for name := range allowedProcessEdgeModelEffectTypes {
		t.Run(name, func(t *testing.T) {
			if !allowedProcessEdgeType("models_effects.go", name) || allowedProcessEdgeType("other.go", name) {
				t.Fatalf("%s must be allowed only in models_effects.go", name)
			}
		})
	}
	pass, diagnostics := shapePass(t, "pkg/services/edges", map[string]string{
		"models_effects.go": "package edges\ntype AssetReadFile func()\ntype Extra struct{}\n",
		"other.go":          "package edges\ntype AssetReadFileElsewhere func()\ntype Edges struct{}\n",
		"helper_test.go":    "package edges\ntype TestOnly struct{}\n",
	})
	pass.Analyzer = ProcessEdges
	if _, err := ProcessEdges.Run(pass); err != nil {
		t.Fatal(err)
	}
	if len(*diagnostics) != 2 {
		t.Fatalf("want two forbidden declarations, got %v", *diagnostics)
	}
	for _, diagnostic := range *diagnostics {
		if !strings.Contains(diagnostic.Message, "process-edge-contract-ownership") || pass.Fset.Position(diagnostic.Pos).Line != 3 && pass.Fset.Position(diagnostic.Pos).Line != 2 {
			t.Fatalf("missing rule/site: %+v", diagnostic)
		}
	}
}

func TestProcessEdgesModelsInterfaceIdentity(t *testing.T) {
	useFixtures(t)
	for _, tc := range []struct {
		name, filename, source string
		want                   bool
	}{
		{"exact", "service_contract.go", "type Service interface{}", false},
		{"missing", "service_contract.go", "type Service struct{}", true},
		{"wrong-name", "service_contract.go", "type Other interface{}", true},
		{"wrong-file", "other.go", "type Service interface{}", true},
		{"extra", "service_contract.go", "type Service interface{}; type Other interface{}", true},
		// The legacy rule counts literal interface declarations, not aliases or
		// interfaces nested in another type. Preserve that exact policy.
		{"alias", "service_contract.go", "type Service = interface{}", false},
	} {
		t.Run(tc.name, func(t *testing.T) {
			pass, diagnostics := shapePass(t, "pkg/services/models", map[string]string{
				tc.filename:      "package models\n" + tc.source,
				"helper_test.go": "package models\ntype TestOnly interface{}",
			})
			pass.Analyzer = ProcessEdges
			if _, err := ProcessEdges.Run(pass); err != nil {
				t.Fatal(err)
			}
			if (len(*diagnostics) != 0) != tc.want {
				t.Fatalf("want violation=%v, got %v", tc.want, *diagnostics)
			}
			if tc.want && !strings.Contains((*diagnostics)[0].Message, "models-root-service-interface") {
				t.Fatal(fmt.Sprint(*diagnostics))
			}
		})
	}
}

