package analyzers

import (
	"testing"

	"golang.org/x/tools/go/analysis/analysistest"
)

func TestTestBoundaryWorkNormalization(t *testing.T) {
	useFixtures(t)
	files := map[string]string{
		"m/pkg/services/work/work.go": `package work
func NormalizeWorkRequest() {}
type Lookalike struct{}
func (Lookalike) NormalizeWorkRequest() {}
`,
		"m/pkg/services/work/work_test.go": `package work
func owner() { NormalizeWorkRequest() }
`,
		"m/pkg/services/work/external_test.go": `package work_test
import "m/pkg/services/work"
func owner() { work.NormalizeWorkRequest() }
`,
		"m/pkg/services/work/child/child_test.go": `package child
import "m/pkg/services/work"
func owner() { work.NormalizeWorkRequest() }
`,
		"m/pkg/services/workers/consumer.go": `package workers
import "m/pkg/services/work"
func production() { work.NormalizeWorkRequest() }
`,
		"m/pkg/services/workers/consumer_test.go": `package workers
import renamed "m/pkg/services/work"
func consumer() {
 renamed.NormalizeWorkRequest() // want "test-work-normalization.*pkg/services/workers.*NormalizeWorkRequest"
 f := renamed.NormalizeWorkRequest // want "test-work-normalization"
 f()
 renamed.Lookalike{}.NormalizeWorkRequest()
 renamed := struct { NormalizeWorkRequest func() }{func(){}}
 renamed.NormalizeWorkRequest()
}
`,
		"m/pkg/services/workers/external_test.go": `package workers_test
import . "m/pkg/services/work"
func consumer() {
 NormalizeWorkRequest() // want "test-work-normalization.*pkg/services/workers_test"
 NormalizeWorkRequest := func() {}
 NormalizeWorkRequest()
}
`,
		"m/internal/testutil/child/support.go": `package child
import . "m/pkg/services/work"
var normalize = NormalizeWorkRequest // want "test-work-normalization"
`,
		"m/tests/functional/internal/support/support.go": `package support
import "m/pkg/services/work"
func helper() { work.NormalizeWorkRequest() } // want "test-work-normalization"
`,
		"m/pkg/services/workers/generated_test.go": `// Code generated by fixture. DO NOT EDIT.
package workers
import "m/pkg/services/work"
func generated() { work.NormalizeWorkRequest() }
`,
		"m/internal/testutility/support.go": `package testutility
import "m/pkg/services/work"
func production() { work.NormalizeWorkRequest() }
`,
		"m/tests/functional/scenario/scenario_test.go": `package scenario
import "m/pkg/services/work"
func scenario() { work.NormalizeWorkRequest() } // want "test-work-normalization"
`,
	}
	dir, cleanup, err := analysistest.WriteFiles(files)
	if err != nil {
		t.Fatal(err)
	}
	defer cleanup()
	analysistest.Run(t, dir, TestBoundary, "m/pkg/services/work", "m/pkg/services/work/child", "m/pkg/services/workers", "m/internal/testutil/child", "m/internal/testutility", "m/tests/functional/internal/support", "m/tests/functional/scenario")
}
