func TestTestBoundaryFunctionalTransportAllowances(t *testing.T) {
	useFixtures(t)
	files := functionalTransportFixtures()
	allowed := `import (
 "m/pkg/transports/cli/clihttp"
 "m/pkg/services/work/transports/cli/submit"
)
func allowed() { clihttp.NewProtocol(); submit.NewSubmit() }
`
	for path, pkg := range map[string]string{
		"m/pkg/services/work/transports/cli/submit/protocol_test.go": "submit_test",
		"m/pkg/transports/cli/clihttp/protocol_test.go":              "clihttp_test",
		"m/internal/testutil/support.go":                             "testutil",
		"m/tests/functionality/scenario_test.go":                     "functionality",
	} {
		files[path] = "package " + pkg + "\n" + allowed
	}
	files["m/tests/functional/scenario/scenario_test.go"] = `package scenario
import (
 "m/pkg/root"
 "m/pkg/transports/http/generated"
 "m/pkg/transports/http/client"
 "m/pkg/transports/cli/clihttp"
 "m/pkg/services/work/transports/cli/submit"
 "m/other/transports"
)
func allowed() {
 root.BuildProcess(); generated.NewPublicValue(); client.NewClient()
 clihttp.Observe(); submit.NewOther(); transports.NewProtocol()
}
`
	dir, cleanup, err := analysistest.WriteFiles(files)
	if err != nil {
		t.Fatal(err)
	}
	defer cleanup()
	analysistest.Run(t, dir, TestBoundary, "m/tests/functional/scenario", "m/pkg/services/work/transports/cli/submit", "m/pkg/transports/cli/clihttp", "m/internal/testutil", "m/tests/functionality")
}

