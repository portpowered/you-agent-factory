func TestPackageBoundaryDebtValidation(t *testing.T) {
	for _, target := range []string{
		"pkg/platform/effects/effects.go#Run#clock#time.Now::count=1",
		"pkg/platform/effects/effects.go#package#opaque-import#os::count=1",
	} {
		if _, err := compilerOwnedKeys("production-default|pkg/platform/effects|" + target); err != nil {
			t.Fatal(err)
		}
	}
	for _, target := range []string{
		"pkg/platform/effects/effects.go#Run#clock#time.Now::count=0",
		"pkg/platform/effects/effects.go#Run#filesystem#time.Now::count=1",
		"pkg/platform/effects/effects_test.go#Run#clock#time.Now::count=1",
		"pkg/neighbor/effects.go#Run#clock#time.Now::count=1",
	} {
		if _, err := compilerOwnedKeys("production-default|pkg/platform/effects|" + target); err == nil {
			t.Fatalf("accepted %s", target)
		}
	}
}

