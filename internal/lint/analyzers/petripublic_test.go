func TestPetriReferencesAllRetiredSymbolsAndOwners(t *testing.T) {
	useFixtures(t)
	files := map[string]string{}
	for owner := range petriReferenceOwners {
		source := "package contracts\n"
		for symbol := range petriReferenceSymbols {
			source += "type " + symbol + " int\n"
		}
		files["m/"+owner+"/p.go"] = source
		consumer := owner + "/consumer"
		source = "package consumer\nimport . \"m/" + owner + "\"\n"
		for symbol := range petriReferenceSymbols {
			source += "var ref" + symbol + " " + symbol + " // want \"petri-reference.*" + symbol + "::count=1\"\n"
		}
		files["m/"+consumer+"/p.go"] = source
	}
	dir, cleanup, err := analysistest.WriteFiles(files)
	if err != nil {
		t.Fatal(err)
	}
	defer cleanup()
	for owner := range petriReferenceOwners {
		analysistest.Run(t, dir, Petripublic, "m/"+owner+"/consumer")
	}
}

