func TestLayeringConstructedServiceEdgesCompilerScope(t *testing.T) {
	useFixtures(t)
	for _, tc := range []struct {
		name, unit, filename, alias, marker, excluded string
		want                                          int
	}{
		{"named", "pkg/services/worker/internal/run", "run.go", "serviceedges", "", "", 1},
		{"blank", "pkg/services/worker", "run.go", "_", "", "", 1},
		{"dot", "pkg/services/worker", "run.go", ".", "", "", 1},
		{"generated", "pkg/services/worker", "run.gen.go", "_", "// Code generated by fixture. DO NOT EDIT.\n", "", 1},
		{"ignored generated", "pkg/services/worker", "run.gen.go", "_", "// Code generated by fixture. DO NOT EDIT.\n", "ignored", 1},
		{"other", "pkg/services/worker", "run.go", "_", "", "other", 1},
		{"ordinary test", "pkg/services/worker", "run_test.go", "_", "", "", 0},
		{"external test", "pkg/services/worker_test", "run_test.go", "_", "", "", 0},
		{"generated test", "pkg/services/worker", "run_test.go", "_", "// Code generated by fixture. DO NOT EDIT.\n", "", 0},
		{"edges owner", "pkg/services/edges", "run.go", "_", "", "", 0},
		{"edges descendant", "pkg/services/edges/sub", "run.go", "_", "", "", 0},
		{"edges neighbor", "pkg/services/edgesextra", "run.go", "_", "", "", 1},
		{"root", "pkg/root", "run.go", "_", "", "", 0},
		{"wire", "pkg/wire", "run.go", "_", "", "", 0},
		{"functional", "tests/functional/smoke", "run_test.go", "_", "", "", 0},
		{"testdata", "pkg/services/worker/testdata/fixture", "run.go", "_", "", "", 0},
	} {
		t.Run(tc.name, func(t *testing.T) {
			fset := token.NewFileSet()
			filename := filepath.Join(t.TempDir(), tc.filename)
			source := tc.marker + "package sample\nimport " + tc.alias + " \"m/pkg/services/edges\"\n"
			file, err := parser.ParseFile(fset, filename, source, parser.ParseComments)
			if err != nil {
				t.Fatal(err)
			}
			var diagnostics []analysis.Diagnostic
			pass := &analysis.Pass{
				Analyzer: Layering, Fset: fset, Files: []*ast.File{file},
				Pkg:      types.NewPackage("m/"+tc.unit, "sample"),
				ReadFile: func(string) ([]byte, error) { return []byte(source), nil },
				Report:   func(d analysis.Diagnostic) { diagnostics = append(diagnostics, d) },
			}
			if tc.excluded != "" {
				pass.Files = []*ast.File{mustParseLayeringSource(t, fset, "base.go", "package sample")}
				if tc.excluded == "ignored" {
					pass.IgnoredFiles = []string{filename}
				} else {
					pass.OtherFiles = []string{filename}
				}
			}
			if _, err := runLayering(pass); err != nil {
				t.Fatal(err)
			}
			if len(diagnostics) != tc.want {
				t.Fatalf("diagnostics=%v, want %d", diagnostics, tc.want)
			}
			for _, d := range diagnostics {
				if !strings.HasPrefix(d.Message, "constructed-service-edges:") || fset.Position(d.Pos).Filename != filename {
					t.Fatalf("unexpected diagnostic: %v", d)
				}
			}
		})
	}
}

func mustParseLayeringSource(t *testing.T, fset *token.FileSet, filename, source string) *ast.File {
	t.Helper()
	file, err := parser.ParseFile(fset, filename, source, parser.ParseComments)
	if err != nil {
		t.Fatal(err)
	}
	return file
}

func TestIgnoredImports(t *testing.T) {
	useFixtures(t)
	// analysistest does not read want comments in IgnoredFiles for custom
	// analyzers. Use the real package loader and observe emitted diagnostics.
	loaded, err := packages.Load(&packages.Config{
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedSyntax | packages.NeedTypes,
		Env:  append(os.Environ(), "GOPATH="+analysistest.TestData(), "GO111MODULE=off", "GOWORK=off"),
	}, "m/pkg/services/ignoredimports")
	if err != nil || len(loaded) != 1 || packages.PrintErrors(loaded) != 0 {
		t.Fatalf("load fixture: %v", err)
	}
	pkg := loaded[0]
	var diagnostics []analysis.Diagnostic
	pass := &analysis.Pass{
		Analyzer: Layering, Fset: pkg.Fset, Files: pkg.Syntax, Pkg: pkg.Types,
		IgnoredFiles: pkg.IgnoredFiles, OtherFiles: pkg.OtherFiles, ReadFile: os.ReadFile,
		Report: func(d analysis.Diagnostic) { diagnostics = append(diagnostics, d) },
	}
	if _, err := runLayering(pass); err != nil {
		t.Fatal(err)
	}
	if len(diagnostics) != 2 {
		t.Fatalf("diagnostics=%v, want two excluded import violations", diagnostics)
	}
	for i, rule := range []string{"constructed-service-edges", "service-subpackage"} {
		position := pkg.Fset.Position(diagnostics[i].Pos)
		if filepath.Base(position.Filename) != "excluded.go" || position.Line != 8-i || !strings.HasPrefix(diagnostics[i].Message, rule+":") {
			t.Fatalf("diagnostic at %v: %s", position, diagnostics[i].Message)
		}
	}
}

func TestIgnoredAndOtherFilesPositions(t *testing.T) {
	useFixtures(t)
	for _, kind := range []string{"ignored", "other"} {
		t.Run(kind, func(t *testing.T) {
			fset := token.NewFileSet()
			file, err := parser.ParseFile(fset, "base.go", "package sample", 0)
			if err != nil {
				t.Fatal(err)
			}
			name := filepath.Join(t.TempDir(), "excluded.go")
			reads := 0
			var diagnostics []analysis.Diagnostic
			pass := &analysis.Pass{
				Analyzer: Layering, Fset: fset, Files: []*ast.File{file},
				Pkg: types.NewPackage("m/pkg/services/sample", "sample"),
				ReadFile: func(path string) ([]byte, error) {
					reads++
					if path != name {
						t.Fatalf("read %q, want %q", path, name)
					}
					// Invalid declarations prove only imports are parsed.
					return []byte("package sample\nimport _ \"m/pkg/services/edges\"\nfunc !invalid"), nil
				},
				Report: func(d analysis.Diagnostic) { diagnostics = append(diagnostics, d) },
			}
			if kind == "ignored" {
				pass.IgnoredFiles = []string{name, "ignored.txt"}
				pass.OtherFiles = []string{name} // repeated compiler inputs are read once
			} else {
				pass.OtherFiles = []string{name, "other.txt"}
			}
			if _, err := runLayering(pass); err != nil {
				t.Fatal(err)
			}
			if reads != 1 || len(diagnostics) != 1 {
				t.Fatalf("reads=%d diagnostics=%v, want one import violation", reads, diagnostics)
			}
			position := fset.Position(diagnostics[0].Pos)
			if position.Filename != name || position.Line != 2 || !strings.Contains(diagnostics[0].Message, "constructed-service-edges|pkg/services/sample|pkg/services/edges") {
				t.Fatalf("diagnostic at %v: %s", position, diagnostics[0].Message)
			}
		})
	}
}

// Compiler-owned inputs preserve the old root-only generated-source policy
// without walking source directories or allowing baseline exemptions.
func TestLayeringGeneratedOnlyCompilerInputs(t *testing.T) {
	useFixtures(t, "generated-only|pkg/transports/http/client|handwritten.go")
	for _, tc := range []struct {
		name, unit, filename, source, excluded string
		want                                   int
	}{
		{"client production", "pkg/transports/http/client", "handwritten.go", "package client", "", 1},
		{"server production", "pkg/transports/http/generated", "handwritten.go", "package generated", "", 1},
		{"ordinary test", "pkg/transports/http/client", "handwritten_test.go", "package client", "", 1},
		{"external test", "pkg/transports/http/client_test", "handwritten_test.go", "package client_test", "", 1},
		{"generated", "pkg/transports/http/client", "client.gen.go", "// Code generated by fixture. DO NOT EDIT.\n\npackage client", "", 0},
		{"late marker", "pkg/transports/http/generated", "fake.gen.go", "package generated\n// Code generated by fixture. DO NOT EDIT.", "", 1},
		{"client descendant", "pkg/transports/http/client/sub", "handwritten.go", "package sub", "", 0},
		{"server descendant", "pkg/transports/http/generated/sub", "handwritten.go", "package sub", "", 0},
		{"neighbor", "pkg/transports/http/clientextra", "handwritten.go", "package clientextra", "", 0},
		{"ignored test", "pkg/transports/http/client_test", "excluded_test.go", "package client_test", "ignored", 1},
		{"other source", "pkg/transports/http/generated", "excluded.go", "package generated", "other", 1},
		{"ignored generated", "pkg/transports/http/client", "excluded.go", "// Code generated by fixture. DO NOT EDIT.\n\npackage client", "ignored", 0},
	} {
		t.Run(tc.name, func(t *testing.T) {
			fset := token.NewFileSet()
			name := filepath.Join(t.TempDir(), tc.filename)
			source := tc.source
			if tc.excluded != "" {
				source = "// Code generated by fixture. DO NOT EDIT.\n\npackage base"
			}
			file, err := parser.ParseFile(fset, name, source, parser.ParseComments)
			if err != nil {
				t.Fatal(err)
			}
			reads := 0
			var diagnostics []analysis.Diagnostic
			pass := &analysis.Pass{
				Analyzer: Layering, Fset: fset, Files: []*ast.File{file},
				Pkg: types.NewPackage("m/"+tc.unit, file.Name.Name),
				ReadFile: func(path string) ([]byte, error) {
					reads++
					if path != name {
						t.Fatalf("unexpected compiler input %q", path)
					}
					return []byte(tc.source), nil
				},
				Report: func(d analysis.Diagnostic) { diagnostics = append(diagnostics, d) },
			}
			if tc.excluded == "ignored" {
				pass.IgnoredFiles = []string{name}
				pass.OtherFiles = []string{name}
			}
			if tc.excluded == "other" {
				pass.OtherFiles = []string{name}
			}
			if _, err := runLayering(pass); err != nil {
				t.Fatal(err)
			}
			if len(diagnostics) != tc.want {
				t.Fatalf("diagnostics=%v, want %d", diagnostics, tc.want)
			}
			if tc.excluded != "" && reads != 1 {
				t.Fatalf("reads=%d, want one compiler input read", reads)
			}
			for _, d := range diagnostics {
				position := fset.Position(d.Pos)
				if position.Filename != name || position.Line != 1 || !strings.HasPrefix(d.Message, "generated-only:") {
					t.Fatalf("unexpected diagnostic at %v: %s", position, d.Message)
				}
			}
		})
	}
}

func TestLayeringGeneratedOnlyUnreadableCompilerInput(t *testing.T) {
	useFixtures(t)
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "client.gen.go", "// Code generated by fixture. DO NOT EDIT.\n\npackage client", parser.ParseComments)
	if err != nil {
		t.Fatal(err)
	}
	unavailable := errors.New("compiler input unavailable")
	pass := &analysis.Pass{
		Analyzer: Layering, Fset: fset, Files: []*ast.File{file},
		Pkg:          types.NewPackage("m/pkg/transports/http/client", "client"),
		IgnoredFiles: []string{"excluded.go"},
		ReadFile:     func(string) ([]byte, error) { return nil, unavailable },
		Report:       func(d analysis.Diagnostic) { t.Fatalf("unexpected diagnostic: %v", d) },
	}
	if _, err := runLayering(pass); !errors.Is(err, unavailable) {
		t.Fatalf("error=%v, want compiler input failure", err)
	}
}
