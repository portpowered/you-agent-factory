func TestDiscoverFileUsesStableFileAndFunctionTargets(t *testing.T) {
	t.Parallel()

	source := []byte(`// backendsizecheck:ignore-file split the file by responsibility.
// pkgmaintcheck:ignore-file-lines split the file by responsibility.
package sample

// backendsizecheck:ignore-function extract the processing stages.
// pkgmaintcheck:ignore-function-lines extract the processing stages.
// pkgmaintcheck:ignore-cyclomatic-complexity replace branching with typed handlers.
func Process() {}
`)
	got, err := DiscoverFile("pkg/sample/process.go", source)
	if err != nil {
		t.Fatalf("DiscoverFile() error = %v", err)
	}
	want := []Directive{
		{Rule: RuleBackendFile, Target: "pkg/sample/process.go", Reason: "split the file by responsibility."},
		{Rule: RuleBackendFunction, Target: "pkg/sample/process.go#Process", Reason: "extract the processing stages."},
		{Rule: RulePackageComplexity, Target: "pkg/sample/process.go#Process", Reason: "replace branching with typed handlers."},
		{Rule: RulePackageFileLines, Target: "pkg/sample/process.go", Reason: "split the file by responsibility."},
		{Rule: RulePackageFuncLines, Target: "pkg/sample/process.go#Process", Reason: "extract the processing stages."},
	}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("DiscoverFile() = %#v, want %#v", got, want)
	}
}

func TestDiscoverCountsOnlyOwnedHandwrittenGoSources(t *testing.T) {
	t.Parallel()

	root := t.TempDir()
	writeDirectiveFile(t, root, "pkg/owned.go", "// pkgmaintcheck:ignore-file-lines split owned.go into focused files.\npackage pkg\n")
	writeDirectiveFile(t, root, "cmd/tool/main.go", "// backendsizecheck:ignore-file split command wiring from execution.\npackage main\n")
	writeDirectiveFile(t, root, "pkg/generated.go", "// Code generated by fixture. DO NOT EDIT.\n// pkgmaintcheck:ignore-file-lines ignored generated content.\npackage pkg\n")
	writeDirectiveFile(t, root, "pkg/transports/http/generated/server.go", "// pkgmaintcheck:ignore-file-lines ignored generated subtree.\npackage generated\n")
	writeDirectiveFile(t, root, "pkg/domain/testdata/fixture.go", "// pkgmaintcheck:ignore-file-lines ignored fixture.\npackage fixture\n")
	writeDirectiveFile(t, root, "pkg/.cache/ignored.go", "// pkgmaintcheck:ignore-file-lines ignored hidden path.\npackage cache\n")
	writeDirectiveFile(t, root, "vendor/example/ignored.go", "// pkgmaintcheck:ignore-file-lines ignored vendor.\npackage example\n")

	got, err := Discover(root, ScopeAllOwned)
	if err != nil {
		t.Fatalf("Discover() error = %v", err)
	}
	want := []Directive{
		{Rule: RuleBackendFile, Target: "cmd/tool/main.go", Reason: "split command wiring from execution."},
		{Rule: RulePackageFileLines, Target: "pkg/owned.go", Reason: "split owned.go into focused files."},
	}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("Discover() = %#v, want only owned handwritten directives %#v", got, want)
	}
}

func TestDiscoverRejectsUnknownScope(t *testing.T) {
	t.Parallel()

	_, err := Discover(t.TempDir(), Scope("unknown"))
	if err == nil || err.Error() != `unsupported exemption discovery scope "unknown"` {
		t.Fatalf("Discover() error = %v, want explicit scope validation", err)
	}
}

func TestRepositoryBaselineAccountsForEveryActiveDirective(t *testing.T) {
	repoRoot := filepath.Join("..", "..")
	data, err := os.ReadFile(filepath.Join(repoRoot, BaselinePath))
	if err != nil {
		t.Fatalf("read repository baseline: %v", err)
	}
	baseline, err := Parse(data)
	if err != nil {
		t.Fatalf("Parse(repository baseline) error = %v", err)
	}
	directives, err := Discover(repoRoot, ScopeAllOwned)
	if err != nil {
		t.Fatalf("Discover(repository) error = %v", err)
	}
	if differences := Compare(directives, baseline); len(differences) != 0 {
		t.Fatalf("repository exemption differences = %#v, want none", differences)
	}
}

func writeDirectiveFile(t *testing.T, root, relativePath, content string) {
	t.Helper()
	path := filepath.Join(root, filepath.FromSlash(relativePath))
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatalf("create parent for %s: %v", relativePath, err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatalf("write %s: %v", relativePath, err)
	}
}
