func TestRenderPagesFromPackageImportsAndMeasuredStatements(t *testing.T) {
	root := t.TempDir()
	alphaDir := filepath.Join(root, "pkg", "services", "alpha")
	innerDir := filepath.Join(alphaDir, "internal", "worker")
	for _, dir := range []string{alphaDir, innerDir} {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			t.Fatal(err)
		}
	}
	if err := os.WriteFile(filepath.Join(alphaDir, "alpha.go"), []byte("package alpha\n\n// comment\nfunc Run() {}\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(innerDir, "worker.go"), []byte("package worker\nfunc Run() {}\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(innerDir, "generated.go"), []byte("// Code generated by fixture. DO NOT EDIT.\npackage worker\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	module := "example.com/repo"
	packages := []backenddependencygraph.Package{
		{ImportPath: module + "/pkg/services/alpha", Dir: alphaDir, GoFiles: []string{"alpha.go"}, Imports: []string{module + "/pkg/services/alpha/internal/worker", module + "/pkg/services/beta"}},
		{ImportPath: module + "/pkg/services/alpha/internal/worker", Dir: innerDir, GoFiles: []string{"worker.go", "generated.go"}},
		{ImportPath: module + "/pkg/services/beta"},
	}
	m, err := buildModel(root, module, packages, map[string]counts{module + "/pkg/services/alpha": {covered: 3, measurable: 4}}, map[string]counts{module + "/pkg/services/alpha": {covered: 1, measurable: 4}}, "abc123")
	if err != nil {
		t.Fatal(err)
	}
	backend := renderBackend(m)
	for _, want := range []string{"# Backend service graph", "## Legend", "[View test coverage](high-level-test-coverage.md)", "| [`alpha`](services/alpha.md) | — |", "s_services_alpha --> s_services_beta", "linkStyle 0 stroke:#475569", "## Service presentations"} {
		if !strings.Contains(backend, want) {
			t.Errorf("backend page missing %q", want)
		}
	}
	if strings.Contains(backend, "imports|") {
		t.Error("dependency diagram still contains numeric edge labels")
	}
	if got := strings.Count(backend, "```mermaid"); got != 1 {
		t.Errorf("backend page has %d diagrams, want only the overview", got)
	}
	if strings.Contains(backend, "Production Go packages under") || strings.Contains(backend, "## Backend families") {
		t.Error("backend page retains inventory explanation")
	}
	if graph, _, found := strings.Cut(backend, "## Legend"); !found || !strings.Contains(graph, "```mermaid") {
		t.Error("service graph must precede legend")
	}
	service := renderOwner(m, "services/alpha")
	for _, want := range []string{"# alpha service architecture", "p1 --> p0", "worker<br/>2 LOC", "[`pkg/services/alpha/internal/worker`](../../../../pkg/services/alpha/internal/worker)", "| worker | 2 | 1 | 1 | XX% | XX% |"} {
		if !strings.Contains(service, want) {
			t.Errorf("service page missing %q", want)
		}
	}
	coverage := renderCoverage(m)
	for _, want := range []string{"75.0% unit<br/>25.0% func", "style s_services_alpha fill:#fde68a", "| [`beta`](services/beta.md) | 0 | XX% | XX% |"} {
		if !strings.Contains(coverage, want) {
			t.Errorf("coverage page missing %q", want)
		}
	}
	if got := strings.Count(coverage, "```mermaid"); got != 1 {
		t.Errorf("coverage overview has %d diagrams, want 1", got)
	}
}

func TestServiceColorsIdentifyRolesWhileCoverageKeepsItsOwnFill(t *testing.T) {
	const module = "example.com/repo"
	work := module + "/pkg/services/work"
	providers := module + "/pkg/services/providers"
	m := model{
		packages: []backenddependencygraph.Package{{ImportPath: work, Imports: []string{providers}}},
		info:     map[string]packageInfo{work: {owner: "services/work"}, providers: {owner: "services/providers"}},
		owners:   []string{"services/providers", "services/work"},
		unit:     map[string]counts{work: {covered: 3, measurable: 4}},
	}
	backend := renderBackend(m)
	for _, want := range []string{
		"style s_services_work fill:#dbeafe,stroke:#1d4ed8",
		"style s_services_providers fill:#ffedd5,stroke:#c2410c",
		"linkStyle 0 stroke:#1d4ed8,stroke-width:2px",
	} {
		if !strings.Contains(backend, want) {
			t.Errorf("backend color missing %q", want)
		}
	}
	coverage := renderCoverage(m)
	if !strings.Contains(coverage, "style s_services_work fill:#fde68a,stroke:#1d4ed8") {
		t.Error("unit coverage fill replaced the service area border")
	}
}

func TestReadCoverageRejectsIncompleteMeasurement(t *testing.T) {
	root := t.TempDir()
	path := filepath.Join(root, "summary.json")
	if err := os.WriteFile(path, []byte(`{"complete":false,"packages":[]}`), 0o644); err != nil {
		t.Fatal(err)
	}
	if _, err := readCoverage(root, path, true); err == nil || !strings.Contains(err.Error(), "incomplete") {
		t.Fatalf("incomplete coverage error = %v", err)
	}
	if _, err := readCoverage(root, "missing.json", true); err == nil {
		t.Fatal("missing required coverage accepted")
	}
}

func TestOverviewKeepsOneDependency(t *testing.T) {
	const module = "example.com/repo"
	alpha := module + "/pkg/services/alpha"
	paths := []string{module + "/pkg/services/beta", module + "/pkg/services/gamma", module + "/pkg/services/delta"}
	m := model{
		packages: []backenddependencygraph.Package{{ImportPath: alpha, Imports: paths}},
		info:     map[string]packageInfo{alpha: {owner: "services/alpha"}},
		owners:   []string{"services/alpha", "services/beta", "services/delta", "services/gamma"},
	}
	for _, path := range paths {
		m.info[path] = packageInfo{owner: ownerOf(strings.TrimPrefix(path, module+"/"))}
	}
	selected := overviewEdges(m)
	if got := len(selected); got != 1 {
		t.Fatalf("overview has %d alpha edges, want 1", got)
	}
	if selected[0].to != "services/beta" {
		t.Fatalf("overview tie-break destination = %s, want services/beta", selected[0].to)
	}
}

